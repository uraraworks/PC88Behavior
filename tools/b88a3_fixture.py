def build():
    body, labels = assemble(SOURCE)
    rom = bytearray(0x2000)
    rom[0x300:0x300+len(body)] = body
    rom[0x38:0x3b] = bytes.fromhex('f3 ed 4d')
    for address, label in {0:'BOOT', 0xc1:'IDLE', 0xed:'DISPATCH', 0x10:'RECV', 0x18:'SEND',
                           0x20:'FDC_OUT', 0x263:'RESULT', 0x2a4:'FDC_OUT', 0x2a7:'FDC_OUT',
                           0x7d6:'SEEK'}.items():
        rom[address:address+3] = b'\xc3' + labels[label].to_bytes(2,'little')
    if 0x300+len(body) > 0x7d6: raise ValueError('対照ROMの容量超過')
    return bytes(rom), labels
