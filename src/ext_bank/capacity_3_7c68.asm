; c1: PSR_DO_MID。自作mainから移動、規則/処理は維持。
    ORG 0x7C68
PSR_DO_MID:
    CALL STRING_EXPR
    LD A,(ERROR_FLAG)
    OR A
    RET NZ
    LD A,(RUN_STR_TMP_LEN)
    LD (RUN_STR_ARG1_LEN),A
    LD HL,RUN_STR_TMP_BUF
    LD DE,RUN_STR_ARG1_BUF
    LD B,A
    CALL CAP_STR_COPY_BN
    LD A,','
    CALL EXPECT_CHAR
    LD A,(ERROR_FLAG)
    OR A
    RET NZ
    CALL PARSE_INT_ARG
    LD A,(ERROR_FLAG)
    OR A
    RET NZ
    LD (RUN_ARG1),DE
    LD A,','
    CALL EXPECT_CHAR
    LD A,(ERROR_FLAG)
    OR A
    RET NZ
    CALL PARSE_INT_ARG
    LD A,(ERROR_FLAG)
    OR A
    RET NZ
    PUSH DE
    LD A,')'
    CALL EXPECT_CHAR
    POP DE
    LD A,(ERROR_FLAG)
    OR A
    RET NZ
    JP MID_COMPUTE
