; c1: INPUT_TARGET。自作mainから移動、規則/処理は維持。
    ORG 0x6449
INPUT_TARGET:
    CALL SKIP_SPACES
    CALL LEX_IDENT_CONSUME
    OR A
    RET Z
    LD (RUN_ASSIGN_KIND),A
    LD HL,IDENT_BUF
    LD DE,RUN_ASSIGN_NAME
    LD BC,8
    LDIR
    CALL SKIP_SPACES
    CALL PEEK_CHAR
    CP '('
    LD HL,0
    RET NZ
    CALL ARRAY_PARSE
    LD A,(ERROR_FLAG)
    OR A
    RET NZ
    CALL ARRAY_GET_OR_CREATE_DEFAULT
    OR A
    RET Z
    JP ARRAY_ELEM_ADDR
