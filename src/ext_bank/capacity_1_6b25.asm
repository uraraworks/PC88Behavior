; c1: LRT_NAMECH。自作mainから移動、規則/処理は維持。
    ORG 0x6B25
LRT_NAMECH:
    CP '.'
    JR Z,_ln_yes
    CP '0'
    JR C,_ln_fold
    CP '9'+1
    JR C,_ln_yes
_ln_fold:
    CALL FOLD_UPPER
    CP 'A'
    JR C,_ln_no
    CP 'Z'+1
    RET
_ln_no:
    OR A
    RET
_ln_yes:
    SCF
    RET

