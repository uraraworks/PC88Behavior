ENTRY_3080_HL_RETURN_VALUE EQU 0F000h ; キーがない道筋だけの戻りHL
ENTRY_3080:
    PUSH BC
    PUSH DE
    LD A,01h
    LD (MM_GAME_WA_E6C3),A
    OUT (0E4h),A
ENTRY_3080_INHIBIT:
    LD A,(MM_GAME_WA_E6CD)
    OR A
    JP NZ,ENTRY_3080_IDLE
    LD A,080h
    OUT (51h),A
    LD A,016h
    OUT (50h),A
    LD A,01h
    OUT (50h),A
    XOR A
    LD (MM_GAME_WA_EFF9),A
    LD HL,MM_GAME_WA_E6D0+11
    LD DE,MM_GAME_WA_E6DC+11
    LD C,11
ENTRY_3080_SCAN:
    LD A,(HL)
    LD (DE),A
    LD B,A
ENTRY_3080_IN:
    IN A,(C)
    CPL
    LD (HL),A
ENTRY_3080_NEXT:
    DEC HL
    DEC DE
    DEC C
    JP P,ENTRY_3080_SCAN
    XOR A
    LD (MM_GAME_WA_EFFF),A
    ; 読取りは降順、押し始めは行・ビットの昇順で処理する。
    LD C,0
ENTRY_3080_EVENT_ROW:
    LD H,0
    LD L,C
    LD DE,MM_GAME_WA_E6DC
    ADD HL,DE
    LD A,(HL)
    PUSH AF                      ; 行の元の前回値を保持
    CPL
    LD DE,-12
    ADD HL,DE
    AND (HL)
    JP Z,ENTRY_3080_NEXT_ROW
    LD B,0
ENTRY_3080_EVENT_BIT:
    PUSH BC
    LD H,0
    LD L,C
    LD DE,MM_GAME_WA_E6D0
    ADD HL,DE
    LD A,(HL)
    LD E,A
    LD D,0
    LD A,B
    OR A
    LD A,1
    JR Z,ENTRY_3080_MASK_READY
ENTRY_3080_MASK:
    ADD A,A
    DJNZ ENTRY_3080_MASK
ENTRY_3080_MASK_READY:
    AND E
    JR Z,ENTRY_3080_SKIP
    LD E,A
    LD HL,3
    ADD HL,SP
    LD A,(HL)
    AND E
    JR NZ,ENTRY_3080_SKIP
    POP BC
    PUSH BC
    ; ファンクションキーは IK_DECODE_MAIN に副作用があるため事前除外。
    LD A,C
    CP 9
    JR NZ,ENTRY_3080_DECODE
    LD A,B
    CP 1
    JR C,ENTRY_3080_DECODE
    CP 6
    JR C,ENTRY_3080_SKIP
ENTRY_3080_DECODE:
    CALL fkey_decode_normal
    OR A
    JR Z,ENTRY_3080_SKIP
    PUSH AF
    LD A,1
    LD (MM_GAME_WA_EFF9),A
    POP AF
    PUSH AF
    POP DE                       ; D=文字コード
    POP BC
    PUSH BC
    LD A,C
    ADD A,A
    ADD A,A
    ADD A,A
    ADD A,B
    LD (MM_GAME_WA_EFFD),A
    LD H,0
    LD L,C
    LD BC,MM_GAME_WA_E6DC
    ADD HL,BC
    LD (MM_GAME_WA_EFFB),HL
    LD BC,-12
    ADD HL,BC
    LD A,(HL)
    LD HL,(MM_GAME_WA_EFFB)
    LD (HL),A
    POP BC
    PUSH BC
    LD A,1
    INC B
ENTRY_3080_EVENT_MASK:
    DEC B
    JR Z,ENTRY_3080_EVENT_MASK_DONE
    ADD A,A
    JR ENTRY_3080_EVENT_MASK
ENTRY_3080_EVENT_MASK_DONE:
    LD (MM_GAME_WA_EFFA),A
    POP BC
    LD A,D
    LD (MM_GAME_WA_EFC6),A       ; フック中の文字を作業域に保持
ENTRY_3080_DELAY:
    LD A,28
    LD (MM_GAME_WA_E6CF),A
    LD A,(MM_GAME_WA_EFFD)
    PUSH BC
    EI
ENTRY_3080_HOOK:
    CALL MM_GAME_WA_ECDF
    POP BC
    LD A,(MM_GAME_WA_EFC6)
    LD (MM_GAME_WA_EFFE),A
    LD A,(MM_GAME_WA_EFFD)
    LD B,A
    AND 7
    LD C,A
    LD A,B
    RRCA
    RRCA
    RRCA
    AND 15
    LD B,C
    LD C,A
    PUSH BC
    CALL ENTRY_3080_PUSH
ENTRY_3080_SKIP:
    POP BC
    INC B
    LD A,B
    CP 8
    JP NZ,ENTRY_3080_EVENT_BIT
ENTRY_3080_NEXT_ROW:
    POP AF
    INC C
    LD A,C
    CP 12
    JP NZ,ENTRY_3080_EVENT_ROW
    LD A,(MM_GAME_WA_EFF9)
    OR A
    JR Z,ENTRY_3080_REPEAT
    LD HL,(MM_GAME_WA_E6CB)
    JR ENTRY_3080_DONE
ENTRY_3080_REPEAT:
    ; 最後に押し始めた文字キーが現在も押されているときだけ反復。
    LD A,(MM_GAME_WA_EFFE)
    OR A
    JR NZ,ENTRY_3080_REPEAT_ACTIVE
    ; 前回もキーなしの場合の走査時間を合わせる。BC とフラグは保存する。
    PUSH BC
    LD B,21
ENTRY_3080_IDLE_WAIT:
    DJNZ ENTRY_3080_IDLE_WAIT
    POP BC
    NOP
    NOP
    JR ENTRY_3080_IDLE
ENTRY_3080_REPEAT_ACTIVE:
    LD HL,(MM_GAME_WA_EFFB)
    LD BC,-12
    ADD HL,BC
    LD A,(MM_GAME_WA_EFFA)
    AND (HL)
    JR Z,ENTRY_3080_RELEASE_DELAY
    LD A,0FFh
    LD (MM_GAME_WA_EFF9),A
    LD HL,MM_GAME_WA_E6CF
    DEC (HL)
    JR NZ,ENTRY_3080_DONE
    LD (HL),KEY_REPEAT_INTERVAL
    CALL ENTRY_3080_PUSH
    JR ENTRY_3080_DONE
ENTRY_3080_PUSH:
    LD HL,0
    LD (MM_GAME_WA_EFC6),HL
    LD HL,(MM_GAME_WA_E6CB)
    LD A,(HL)
    INC A
    LD C,A
    INC HL
    LD B,(HL)
    INC HL
    INC HL
    LD A,(HL)
    AND C
    CP B
ENTRY_3080_FULL:
    RET Z
    LD E,A
    LD D,0
    INC HL
    LD C,(HL)
    INC HL
    LD B,(HL)
    LD H,B
    LD L,C
    ADD HL,DE
    LD A,(MM_GAME_WA_EFFE)
ENTRY_3080_STORE:
    LD (HL),A
    LD HL,(MM_GAME_WA_E6CB)
    LD (HL),E
    RET
ENTRY_3080_IDLE:
    LD HL,0750h
    PUSH HL
    POP AF
    LD HL,ENTRY_3080_HL_RETURN_VALUE
ENTRY_3080_DONE:
    LD A,07h
    LD (MM_GAME_WA_E6C3),A
ENTRY_3080_OUT:
    OUT (0E4h),A
    POP DE
    POP BC
ENTRY_3080_RET:
    EI
    RET

; 解放後も EFFE は残るため、この経路にもキーなしの待ちを置く。
ENTRY_3080_RELEASE_DELAY:
    PUSH BC
    LD B,16
ENTRY_3080_RELEASE_WAIT:
    DJNZ ENTRY_3080_RELEASE_WAIT
    POP BC
    JP ENTRY_3080_IDLE

ENTRY_35CE:
    PUSH BC
    PUSH HL
    LD C,A                      ; 空のとき入口のAを返す
    LD HL,(MM_GAME_WA_E6CB)
    INC HL
    INC HL
    LD A,(HL)
    OR A
    JR NZ,ENTRY_35CE_LOOKAHEAD
    DEC HL
    LD B,(HL)
    DEC HL
    LD A,(HL)
    CP B
ENTRY_35CE_EMPTY_CHECK:
    JR Z,ENTRY_35CE_EMPTY
    LD A,B
    INC A
    INC HL
    INC HL
    INC HL
    AND (HL)
    LD C,A
    LD B,0
    INC HL
    LD A,(HL)
    INC HL
    LD H,(HL)
    LD L,A
    ADD HL,BC
    LD B,(HL)
    LD HL,(MM_GAME_WA_E6CB)
    INC HL
    LD (HL),C
ENTRY_35CE_ADVANCE:
    INC HL
    LD (HL),0
    LD A,B
    JR ENTRY_35CE_RETURN
ENTRY_35CE_LOOKAHEAD:
    LD (HL),0
    JR ENTRY_35CE_RETURN
ENTRY_35CE_EMPTY:
    LD A,C
    CP A
    POP HL
    POP BC
    RET
ENTRY_35CE_RETURN:
    OR A                        ; 文字の符号・ゼロ・パリティを返す
    POP HL
    POP BC
    RET
