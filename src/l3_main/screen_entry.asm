ENTRY_7071_DE_RETURN_VALUE EQU 0FF80h
ENTRY_7071_HL_RETURN_VALUE EQU 0E616h
ENTRY_6F6B_WAIT_N EQU 14662   ; 26*14662+101 = 381313T 追加
ENTRY_7071_WAIT_N EQU 14468   ; 26*14468+74 = 376242T 追加
ENTRY_7071:
    ; main-rom-entry.md 1.8節: 公式の最頻値 378058T に合わせる待ち。
    ; 自作の待ち前は 1823T(G5 無入力、境界時系列で計時)。追加は 26n+74T。
    PUSH AF
    PUSH BC
    LD BC,ENTRY_7071_WAIT_N
    CALL ENTRY_WAIT_BC
    POP BC
    POP AF
    PUSH AF
    CALL MM_GAME_WA_ED36
ENTRY_7071_RETURN:
    LD HL,MM_GAME_WA_E60D
    CALL ENTRY_7071_RESTORE
    CALL ENTRY_7071_RESTORE
    CALL ENTRY_7071_RESTORE
    CALL ENTRY_7071_RESTORE
    INC HL
    POP AF
    ; 共通処理へ渡す戻り値をスタックに用意する。
    LD H,A
    LD L,054h
    PUSH HL
ENTRY_7071_REGS:
    LD HL,0000h
    PUSH HL
    LD HL,ENTRY_7071_DE_RETURN_VALUE
    PUSH HL
    LD HL,ENTRY_7071_HL_RETURN_VALUE
    PUSH HL
    JP ENTRY_6F6B_COMMON

ENTRY_6F6B:
    ; main-rom-entry.md 1.8節: 公式の最頻値 460709T に合わせる待ち。
    ; 自作の待ち前は 79401T(G5 無入力、境界時系列で計時)。待ちは 6F6B から
    ; 入ったときだけで、7071 から共通部分へ来る道には入れない。追加は 26n+101T。
    CALL ENTRY_6F6B_BODY
    PUSH AF
    PUSH BC
    LD BC,ENTRY_6F6B_WAIT_N
    CALL ENTRY_WAIT_BC
    POP BC
    POP AF
    RET
ENTRY_6F6B_BODY:
    PUSH HL
    LD HL,0044h
    PUSH HL
    LD HL,02000h
    PUSH HL
    LD HL,00400h
    PUSH HL
    ; 並びを共通の HL, DE, BC, AF にする。
    POP DE
    POP BC
    POP AF
    POP HL
    PUSH AF
    PUSH BC
    PUSH DE
    PUSH HL
ENTRY_6F6B_COMMON:
    PUSH IX
    PUSH IY
    LD A,3
    LD (MM_SCR_MODE),A
    LD HL,(25<<8)|80
    LD (MM_FN_AUX),HL
    LD HL,25<<8
    LD (MM_SCR_WTOP),HL
    LD D,1
    LD A,I                     ; CRTC設定中のVSYNC割り込みを抑止
    PUSH AF
    DI
    CALL SCREEN_MODE_APPLY
    POP AF
    JP PO,ENTRY_6F6B_MODE_DONE
    EI
ENTRY_6F6B_MODE_DONE:
    LD HL,07FC0h
    XOR A
    CALL EXT_BANK_CALL
ENTRY_6F6B_CLS:
    CALL CLS_SCREEN
ENTRY_7071_CURSOR:
    LD HL,0101h
    LD (MM_GAME_WA_EF86),HL
ENTRY_6F6B_EI:
    EI
    POP IY
    POP IX
    POP HL
    POP DE
    POP BC
    POP AF
ENTRY_7071_RET:
    RET
ENTRY_7071_RESTORE:
    IN A,(0x71)
    OUT (0x71),A
    OUT (0x71),A
    INC HL
    INC HL
    RET
; BC 回の待ち(26*BC-5T+RET)。A・F・BC を壊す。
ENTRY_WAIT_BC:
    DEC BC
    LD A,B
    OR C
    JR NZ,ENTRY_WAIT_BC
    RET
